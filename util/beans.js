class Room{

    constructor(id, name, shortname, available, maxpersons, address, price, lat, lon){
        this.id = id;
        this.name = name;
        this.shortname = shortname;
        this.available = available;
        this.maxpersons = maxpersons; 
        this.address = address;
        this.price = price;
        this.lat = lat;
        this.lon = lon;
    }

}